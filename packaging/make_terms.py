# ---------------------------------------------------------------- 条款正文
# 写法约定：以 "# " 开头是一级标题，"## " 是二级标题，空行分段。

#: 打包脚本的位置（用来找 shell/package.json）
_ROOT = Path(__file__).resolve().parents[1]
_SHELL_PKG = _ROOT / "shell" / "package.json"


def _app_version() -> str:
    """取应用版本号（唯一来源：shell/package.json），读不到返回 "unknown"。

    **为什么不再在条款里写死版本号**（2026-11-24）：
    原来是 `版本 1.1.0` 硬编码，而软件版本已经是 1.2.1 ——
    安装向导第一屏显示的免责声明写着过时的版本号。
    每次发版还要人记得手改，迟早忘。
    改成从 package.json 读，永远不会脱节。
    """
    try:
        return str(json.loads(_SHELL_PKG.read_text(encoding="utf-8"))["version"])
    except Exception:                                # noqa: BLE001
        return "unknown"


def terms_text() -> str:
    """渲染后的条款正文（版本号与生效日期已填好）。

    生效日期取**构建当天**：条款随版本一起发布，日期应当反映
    "这一版是什么时候生效的"，而不是某个写死的过去日期。
    """
    import time as _time
    today = _time.strftime("%Y 年 %m 月 %d 日")
    return TERMS.replace("{VERSION}", _app_version()).replace("{DATE}", today)


