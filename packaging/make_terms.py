    root = Path(__file__).resolve().parents[1]
    out_dir = Path(args.out) if args.out else (root / "shell" / "build")
    out_dir.mkdir(parents=True, exist_ok=True)

    rtf = out_dir / "terms.rtf"
    txt = out_dir / "terms.txt"
    # 用**渲染后**的正文（版本号/日期已填），不是原始模板 2026-11-24
    body = terms_text()
    rtf.write_text(build_rtf(body), encoding="utf-8")
    txt.write_text(body, encoding="utf-8")
    chars = len(body)
    print(f"许可条款已生成：{rtf}（{rtf.stat().st_size} 字节）")
    print(f"纯文本副本：{txt}（{chars} 字）")
    return 0


