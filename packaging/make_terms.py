def _rtf_escape(text: str) -> str:
    out: list[str] = []
    for ch in text:
        if ch in "\\{}":
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\par\n")
        elif ord(ch) < 128:
            out.append(ch)
        else:
            # RTF 用 \uN? 表示 Unicode 字符（? 是该字符的 ASCII 占位，\uc1 只吃一个）
            out.append("\\u%d?" % ord(ch))
    return "".join(out)


def build_rtf(text: str) -> str:
    """极简 RTF：标题加粗、正文常规、稍宽行距。字体用雅黑（中文不易糊）。"""
    body: list[str] = []
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line.strip():
            body.append("\\par")
            continue
        if line.startswith("# "):
            body.append("\\pard\\sb160\\sa80\\b\\fs26 " + _rtf_escape(line[2:]) + "\\b0\\fs20\\par")
        elif line.startswith("## "):
            body.append("\\pard\\sb120\\sa60\\b\\fs22 " + _rtf_escape(line[3:]) + "\\b0\\fs20\\par")
        elif line.startswith(("一、", "二、", "三、", "四、", "五、", "六、", "七、", "八、",
                              "九、", "十、", "十一、", "十二、", "十三、", "十四、", "十五、")):
            body.append("\\pard\\sb120\\sa60\\b\\fs22 " + _rtf_escape(line) + "\\b0\\fs20\\par")
        else:
            body.append("\\pard\\sl260\\slmult1 " + _rtf_escape(line) + "\\par")
    return (
        "{\\rtf1\\ansi\\ansicpg936\\deff0\\uc1"
        "{\\fonttbl{\\f0\\fnil\\fcharset134 Microsoft YaHei;}}\\f0\\fs20\n"
        + "\n".join(body)
        + "\n}\n"
    )


